export const eventos = pgTable(
  "eventos",
  {
    id: bigint("id", { mode: "number" }).primaryKey().generatedByDefaultAsIdentity(),
    organizadorId: bigint("organizador_id", { mode: "number" }).notNull(),
    nombre: varchar("nombre", { length: 200 }).notNull(),
    descripcion: text("descripcion"),
    fechaEvento: timestamp("fecha_evento", { withTimezone: true }).notNull(),
    lugar: varchar("lugar", { length: 200 }),
    aficheUrl: varchar("afiche_url", { length: 255 }),
    aforoTotal: integer("aforo_total"),
    esGratuito: boolean("es_gratuito").notNull().default(false),
    aprobacionGratuito: text("aprobacion_gratuito").notNull().default("no_aplica"),
    estado: text("estado").notNull().default("borrador"),
    fechaEventoOriginal: timestamp("fecha_evento_original", { withTimezone: true }),
    creadoEn: timestamp("creado_en", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("idx_eventos_organizador").on(t.organizadorId),
    // Listado público + sitemap + home: solo se busca por fecha entre los publicados.
    index("idx_eventos_publicos")
      .on(t.fechaEvento)
      .where(sql`${t.estado} = 'publicado'`),
    foreignKey({
      name: "fk_eventos_organizador",
      columns: [t.organizadorId],
      foreignColumns: [usuarios.id],
    }).onDelete("restrict"),
    check("chk_eventos_aforo_no_negativo", sql`${t.aforoTotal} is null or ${t.aforoTotal} >= 0`),
    checkEnum("chk_eventos_aprobacion_gratuito", t.aprobacionGratuito, APROBACION_GRATUITO),
    checkEnum("chk_eventos_estado", t.estado, ESTADOS_EVENTO),
  ],
);

