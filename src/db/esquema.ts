/**
 * Esquema PostgreSQL — traducción de sql/schema.sql (MariaDB) del proyecto PHP.
 * Ver plan de migración §4 para las decisiones de traducción. Resumen:
 *  - BIGINT UNSIGNED AUTO_INCREMENT → bigint GENERATED BY DEFAULT AS IDENTITY
 *    ("by default", no "always": permite insertar IDs explícitos en la
 *    migración de datos sin OVERRIDING SYSTEM VALUE).
 *  - ENUM(...) → text + CHECK (no CREATE TYPE nativo — ver §4.2: la migración
 *    de datos es más simple y agregar/quitar valores no reescribe la tabla).
 *    Los dominios viven en una sola fuente de verdad: src/lib/constantes.ts.
 *  - DECIMAL(12,0)/DECIMAL(14,0) (montos en guaraníes, sin decimales) →
 *    bigint + CHECK >= 0 (no numeric: llegaría como string por el driver).
 *  - DATETIME → timestamp with time zone (timestamptz). La zona horaria de
 *    aplicación es America/Asuncion (ver §4.4) — la migración de datos
 *    convierte explícitamente, nunca implícitamente.
 *  - Los 2 triggers de borrado (trg_tandas_delete_bd, trg_eventos_delete_bd)
 *    y el nuevo trigger de tickets.actualizado_en no son representables acá
 *    (Drizzle no genera plpgsql) — viven en una migración SQL a mano
 *    (drizzle/0001_triggers.sql, generada con `drizzle-kit generate --custom`).
 *  - Los FK se dejan DEFERRABLE INITIALLY IMMEDIATE en esa misma migración a
 *    mano, para que el script de migración de datos pueda cargar las 13
 *    tablas dentro de una única transacción con constraints diferidos.
 */

function checkEnum(
  nombre: string,
  columna: ExtraConfigColumn,
  valores: readonly string[],
) {
  const lista = valores.map((v) => `'${v}'`).join(", ");
  return check(nombre, sql`${columna} in (${sql.raw(lista)})`);
}

// ---------------------------------------------------------------------------
// usuarios — los 4 roles en una sola tabla
// ---------------------------------------------------------------------------
export const usuarios = pgTable(
  "usuarios",
  {
    id: bigint("id", { mode: "number" }).primaryKey().generatedByDefaultAsIdentity(),
    nombre: varchar("nombre", { length: 150 }).notNull(),
    email: varchar("email", { length: 150 }).notNull(),
    passwordHash: varchar("password_hash", { length: 255 }).notNull(),
    rol: text("rol").notNull(),
    telefono: varchar("telefono", { length: 30 }),
    cedula: varchar("cedula", { length: 30 }),
    estado: text("estado").notNull().default("activo"),
    motivoRechazo: varchar("motivo_rechazo", { length: 255 }),
    rucFacturacion: varchar("ruc_facturacion", { length: 30 }),
    tycAceptadoEn: timestamp("tyc_aceptado_en", { withTimezone: true }),
    invitadoPor: bigint("invitado_por", { mode: "number" }),
    creadoEn: timestamp("creado_en", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // MariaDB compara emails sin distinguir mayúsculas (collation *_ci);
    // Postgres es case-sensitive por defecto. Este índice + el login por
    // lower(email) replican esa semántica (ver plan §7.5, validación #10).
    uniqueIndex("uq_usuarios_email_lower").on(sql`lower(${t.email})`),
    foreignKey({
      name: "fk_usuarios_invitado_por",
      columns: [t.invitadoPor],
      foreignColumns: [t.id],
    }).onDelete("set null"),
    checkEnum("chk_usuarios_rol", t.rol, ROLES),
    checkEnum("chk_usuarios_estado", t.estado, ESTADOS_USUARIO),
  ],
);

